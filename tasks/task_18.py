import os
import pandas as pd

pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "students_data.csv")

myData = pd.read_csv(CSV_PATH)
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

print("=" * 80)
print('18. Таңдалған көрсеткіштің 25, 50 және 75-процентильдерін табыңыз.')
print("Pandas әдістері:", 'quantile()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
q_table = myData[["GPA", "Емтихан_балы", "Қатысу_пайызы"]].quantile([0.25, 0.50, 0.75])
print(q_table)

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• quantile([0.25, 0.50, 0.75]) — деректерді төрт тең бөлікке бөлетін квартильдік шектерді (25%, 50% медиана, 75%) есептейді.\nCSV бойынша талдау: Студенттердің 25%-ында GPA 2.73-ден төмен, 50%-ында (медиана) 2.98-ден төмен, ал ең үздік 25% студенттің GPA көрсеткіші 3.23-ден жоғары (4.00-ге дейін).')
print("-" * 80)
