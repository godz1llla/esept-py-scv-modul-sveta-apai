# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: myData.shape — кестенің өлшемін (жолдар_саны, бағандар_саны) түрінде қайтарады: (600, 12).
# Назар аудар: shape соңында жақша () қойылмайды, себебі бұл функция емес, кестенің қасиеті (атрибуты).
# ШАГ 1: myData.shape показывает размер таблицы в виде пары чисел (строки, столбцы): (600, 12).
# Важно: после shape скобки () НЕ ставятся, так как это свойство (атрибут) таблицы, а не метод.
print("Кесте өлшемі (shape):", myData.shape)

# 2-ҚАДАМ: myData.shape[0] — (600, 12) жұбының бірінші санын (индекс 0), яғни жолдар санын (600) алады.
# ШАГ 2: myData.shape[0] берет первое число из пары (600, 12) — то есть количество строк (600 студентов).
print("Жолдар саны:", myData.shape[0])

# 3-ҚАДАМ: myData.shape[1] — (600, 12) жұбының екінші санын (индекс 1), яғни бағандар санын (12) алады.
# ШАГ 3: myData.shape[1] берет второе число из пары (600, 12) — то есть количество столбцов (12).
print("Бағандар саны:", myData.shape[1])

# 4-ҚАДАМ: myData.columns — кестенің барлық баған атауларын алады, ал .tolist() оны қарапайым
# Python тізіміне ['Студент_ID', 'Аты_жөні', ...] айналдырады.
# ШАГ 4: myData.columns хранит названия всех столбцов, а .tolist() превращает их в красивый список Python.
print("Баған атаулары:", myData.columns.tolist())

