import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('4. Сандық бағандардың негізгі статистикалық сипаттамаларын алыңыз.')
print("Pandas әдістері:", 'describe()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
print(myData.describe())

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• describe() әдісі кестедегі барлық 7 сандық баған бойынша негізгі статистикалық көрсеткіштерді автоматты түрде есептейді: саны (count), орташа мәні (mean), стандартты ауытқуы (std), ең кіші мәні (min), 25%, 50% (медиана), 75% квартильдері және ең үлкен мәні (max).\nCSV бойынша талдау: Кестеде орташа жарнама шығыны 72.50 бірлікті, орташа көрілім саны 6749.78, орташа клиент саны 89.98, орташа тапсырыс саны 52.44, орташа сатылым көлемі 524.25, ал орташа таза пайда 134.76 бірлікті құрайды. Ең төменгі пайда — 48, ал ең жоғарғы пайда — 223.')
print("-" * 80)
