# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: myData.sort_values(by=["Факультет", "GPA"], ascending=[True, False]) —
# кестені бірден ЕКІ баған бойынша сұрыптайды:
#   1) Алдымен 'Факультет' бойынша: ascending=True (А-дан Я-ға қарай әліпби ретімен).
#   2) Әр факультеттің ішінде 'GPA' бойынша: ascending=False (ең жоғары GPA-дан төменге қарай, кему ретімен).
# ШАГ 1: myData.sort_values() сортирует таблицу сразу по двум столбцам:
#   - Параметр by=["Факультет", "GPA"] указывает, по каким столбцам сортировать.
#   - Параметр ascending=[True, False] задает направление:
#     True для 'Факультет' = по возрастанию (по алфавиту от А до Я),
#     False для 'GPA' = по убыванию (от самого большого GPA 3.96 к меньшему).
sorted_data = myData.sort_values(by=["Факультет", "GPA"], ascending=[True, False])

# 2-ҚАДАМ: Сұрыпталған кестенің алғашқы 10 жолын экранға шығарамыз:
# ШАГ 2: Выводим первые 10 строк отсортированной таблицы:
print(sorted_data[["Студент_ID", "Аты_жөні", "Факультет", "Мамандық", "Курс", "Емтихан_балы", "GPA", "Стипендия"]].head(10))

