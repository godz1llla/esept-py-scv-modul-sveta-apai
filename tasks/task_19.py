print("-" * 80)
print("Подробное объяснение простыми словами (По-русски):")
print("1. Что такое мода .mode(): Мода — это самое популярное значение в столбце (от слова «модный»). Например, самый популярный факультет — 'Ақпараттық технологиялар' (209 чел.), самый частый город — 'Алматы' (173 чел.).\n2. Что делает .value_counts(): Если .mode() называет только победителя (1-е место), то .value_counts() расписывает полную статистику: сколько именно раз встретилось каждое значение (например: Грант — 371 студент, Ақылы — 229 студентов).")
