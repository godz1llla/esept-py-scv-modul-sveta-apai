# 1-ҚАДАМ: myData.nsmallest(5, "GPA") — 'GPA' бағаны бойынша ең төменгі балл алған
# 5 студентті өсу ретімен (ең азынан бастап) тауып береді.
# ШАГ 1: myData.nsmallest(5, "GPA") — противоположность nlargest: находит 5 строк
# с самыми маленькими значениями в столбце 'GPA' (5 студентов с самым низким GPA).
bottom5_gpa = myData.nsmallest(5, "GPA")

# 2-ҚАДАМ: Табылған 5 студенттің мәліметтерін экранға шығарамыз:
# ШАГ 2: Выводим эти 5 строк на экран:
