import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('19. Ең жиі кездесетін мәнді анықтаңыз.')
print("Pandas әдістері:", 'mode(), value_counts()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
print("Ең жиі сатылатын өнім (mode):", myData["Өнім атауы"].mode()[0])
print("Ең жиі кездесетін қала (mode):", myData["Қала"].mode()[0])
print("\nӨнімдер бойынша жазбалар саны (value_counts):")
print(myData["Өнім атауы"].value_counts())
print("\nЖарнама түрлері бойынша жазбалар саны (value_counts):")
print(myData["Жарнама түрі"].value_counts())

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• mode() әдісі бағандағы ең жиі қайталанатын мәнді (моданы) табады.\n• value_counts() әдісі бағандағы әрбір мәннің неше рет кездесетінін санап, кему ретімен шығарады.\nCSV бойынша талдау: Ең жиі кездесетін тауар — Телефон (151 рет), ал қалған тауарлар да шамалас (Ноутбук — 150, Құлаққап — 150, Планшет — 149). Жарнама арналары бойынша Instagram бірінші орында (201 жазба), TikTok — 200, Google — 199.')
print("-" * 80)
