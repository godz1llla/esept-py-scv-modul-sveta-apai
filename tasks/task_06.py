# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: myData.isnull() — кестедегі әрбір ұяшықты тексереді:
# егер ұяшық бос (NaN) болса — True (1), егер ішінде дерек болса — False (0) қайтарады.
# Ал оған .sum() жалғасақ — әр баған бойынша барлық True (1) мәндерін қосып, бос ұяшықтар санын шығарады.
# ШАГ 1: myData.isnull() проверяет каждую ячейку таблицы на пустоту (True = пусто, False = заполнено).
# А .sum() складывает все True (как единички) по каждому столбцу и показывает, сколько пропусков в каждом столбце.
print("Әр бағандағы бос (NaN) мәндер саны:")
print(myData.isnull().sum())

# 2-ҚАДАМ: myData.isnull().sum().sum() — екінші рет .sum() жазу арқылы барлық 12 бағандағы
# бос мәндерді бір-біріне қосып, бүкіл кесте бойынша ЖАЛПЫ бос ұяшықтар санын (0) табамыз.
# ШАГ 2: Второй .sum() складывает результаты всех 12 столбцов вместе и дает ОБЩЕЕ число пропусков во всей таблице (0).
print("Жалпы бос мәндер саны:", myData.isnull().sum().sum())

