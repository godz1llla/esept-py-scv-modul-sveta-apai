import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('18. Таңдалған көрсеткіштің 25, 50 және 75-процентильдерін табыңыз.')
print("Pandas әдістері:", 'quantile()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
q_sales = myData["Сатылым көлемі"].quantile([0.25, 0.50, 0.75])
q_profit = myData["Пайда"].quantile([0.25, 0.50, 0.75])
print("Сатылым көлемі процентильдері:\n", q_sales)
print("Пайда процентильдері:\n", q_profit)

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• quantile([0.25, 0.50, 0.75]) әдісі деректерді төрт тең бөлікке бөлетін квартильдік (процентильдік) шектерді есептейді.\nCSV бойынша талдау: 'Сатылым көлемі' бойынша 25-процентиль — 391.5, 50-процентиль (медиана) — 529.5, ал 75-процентиль — 663.25. Демек, барлық сатылымдардың 75%-ында түсім 663.25 бірліктен аспайды, ал ең үздік 25% сатылымдар 663.25-тен жоғары нәтиже көрсеткен.")
print("-" * 80)
