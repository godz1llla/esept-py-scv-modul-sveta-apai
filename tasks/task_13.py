import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('13. Таңдалған көрсеткіш (Сатылым көлемі) бойынша ең үлкен мәндері бар 10 жазбаны табыңыз.')
print("Pandas әдістері:", 'nlargest()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
top10 = myData.nlargest(10, "Сатылым көлемі")
print(top10[["№", "Күні", "Өнім атауы", "Қала", "Жарнама түрі", "Сатылым көлемі", "Пайда"]])

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• nlargest(10, 'Сатылым көлемі') әдісі бүкіл кестені сұрыптамай-ақ, 'Сатылым көлемі' бағаны бойынша ең жоғары 10 жазбаны жылдам тауып береді.\nCSV бойынша талдау: Ең жоғары сатылым көлемі 817 бірлікті құрайды (Алматы қаласы, Телефон, 16.04.2028, пайдасы — 212). ТОП-10 тізіміне сатылым көлемі 802-ден 817-ге дейінгі ең табысты науқандар енді.")
print("-" * 80)
