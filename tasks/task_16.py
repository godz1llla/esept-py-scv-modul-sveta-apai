import os
import pandas as pd

pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "students_data.csv")

myData = pd.read_csv(CSV_PATH)
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

print("=" * 80)
print('16. Сандық көрсеткіштердің орташа мәнін, медианасын, минимумын және максимумын есептеңіз.')
print("Pandas әдістері:", 'mean(), median(), min(), max()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]
stats_16 = pd.DataFrame({
    "Орташа мән (mean)": myData[num_cols].mean().round(2),
    "Медиана (median)": myData[num_cols].median().round(2),
    "Минимум (min)": myData[num_cols].min(),
    "Максимум (max)": myData[num_cols].max()
})
print(stats_16)

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• mean() — арифметикалық орташа мәнді, median() — реттелген қатардың дәл ортасындағы медиананы, min() — ең кіші мәнді, max() — ең үлкен мәнді есептейді.\nCSV бойынша талдау: Барлық сандық бағандарда орташа мән мен медиана бір-біріне өте жақын (мысалы, GPA орташасы — 2.98, медианасы — 2.98; Емтихан балының орташасы — 79.45, медианасы — 79.00). Бұл студенттер үлгерімінің қалыпты (симметриялы) таралғанын дәлелдейді.')
print("-" * 80)
