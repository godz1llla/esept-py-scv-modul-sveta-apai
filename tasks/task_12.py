# ==============================================================================
# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: & (ЖӘНЕ / И) операторы арқылы бірден 3 шартты тексереміз:
#   1) Факультеті == 'Ақпараттық технологиялар' БОЛСЫН, ЖӘНЕ (&)
#   2) Оқу түрі == 'Грант' БОЛСЫН, ЖӘНЕ (&)
#   3) GPA балы > 3.2 БОЛСЫН.
# Маңызды ереже: Pandas-та әрбір шарт міндетті түрде жеке жақшаға (...) алынуы керек!
# ШАГ 1: Используем метод .loc[] и оператор & (логическое И — все условия должны выполниться одновременно):
#   1) Факультет == 'Ақпараттық технологиялар' И (&)
#   2) Оқу_түрі == 'Грант' И (&)
#   3) GPA > 3.2.
# Важное правило Pandas: каждое условие обязательно берется в круглые скобки (...)!
filter_and = myData.loc[
    (myData["Факультет"] == "Ақпараттық технологиялар") &
    (myData["Оқу_түрі"] == "Грант") &
    (myData["GPA"] > 3.2)
]
print("1) АТ факультетінде грантта оқитын және GPA > 3.2 студенттер саны:", len(filter_and))

# 2-ҚАДАМ: | (НЕМЕСЕ / ИЛИ) операторы арқылы 2 шарттың кемінде біреуі орындалатын жолдарды табамыз:
# Студент Алматы қаласынан НЕМЕСЕ (|) Астана қаласынан болса жеткілікті.
# ШАГ 2: Используем оператор | (логическое ИЛИ — достаточно выполнения хотя бы одного условия):
# Выбираем студентов, которые приехали из Алматы ИЛИ из Астаны.
filter_or = myData.loc[(myData["Қала"] == "Алматы") | (myData["Қала"] == "Астана")]
print("2) Алматы немесе Астана қаласынан келген студенттер саны:", len(filter_or))

# Бірінші фильтрден өткен үздік грант студенттерінің алғашқы 8-ін экранға шығарамыз:
# Выводим первые 8 найденных студентов из первого фильтра:
print(filter_and.head(8))

