import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('6. Бос мәндерді тауып, әр бағандағы олардың санын есептеңіз.')
print("Pandas әдістері:", 'isnull(), sum()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
print(myData.isnull().sum())
print("Барлық бос мәндер саны:", myData.isnull().sum().sum())

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• isnull() әдісі кестенің әрбір ұяшығын тексеріп, егер мән бос (NaN) болса True, ал толық болса False қайтарады.\n• sum() әдісі сол True мәндерін қосып, әр бағандағы бос ұяшықтардың нақты санын есептейді.\nCSV бойынша талдау: Барлық 13 бағанда да бос мәндер саны 0-ге тең. Бұл маркетингтік деректер жиынының толық екенін және ешбір жазбада мәлімет қалып кетпегенін білдіреді.')
print("-" * 80)
