print("Pandas әдістері:", 'nunique(), unique()')
print("=" * 80 + "\n")

# ==============================================================================
# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: myData.nunique() — (number of unique) әр бағанда НЕШЕ қайталанбайтын (бірегей)
# мән бар екенін санмен шығарады (мысалы: Факультет — 5, Мамандық — 8, Курс — 4, Қала — 6).
# ШАГ 1: myData.nunique() (от англ. Number of Unique) считает, СКОЛЬКО неповторяющихся вариантов
# есть в каждом столбце (например, всего 5 факультетов, 8 специальностей, 6 городов, 2 формы обучения).
print("Әр бағандағы бірегей мәндер саны:")
print(myData.nunique())

# 2-ҚАДАМ: myData["Факультет"].unique() — тек санын емес, сол 5 факультеттің НАҚТЫ АТАУЛАРЫН тізіммен шығарады.
# ШАГ 2: myData["Факультет"].unique() выводит уже не количество, а САМИ НАЗВАНИЯ этих 5 уникальных факультетов.
print("\nФакультеттер:", myData["Факультет"].unique())

# 3-ҚАДАМ: Мамандық бағанындағы 8 бірегей мамандықтың атауын шығарамыз:
# ШАГ 3: Выводим список всех 8 уникальных специальностей:
print("Мамандықтар:", myData["Мамандық"].unique())

# 4-ҚАДАМ: Қала бағанындағы 6 қаланың атауын шығарамыз:
# ШАГ 4: Выводим список всех 6 уникальных городов:
print("Қалалар:", myData["Қала"].unique())

# 5-ҚАДАМ: Оқу_түрі бағанындағы 2 оқу түрін ('Грант', 'Ақылы') шығарамыз:
# ШАГ 5: Выводим варианты формы обучения ('Грант', 'Ақылы'):
print("Оқу түрі:", myData["Оқу_түрі"].unique())

