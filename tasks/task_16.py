import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('16. Сандық көрсеткіштердің орташа мәнін, медианасын, минимумын және максимумын есептеңіз.')
print("Pandas әдістері:", 'mean(), median(), min(), max()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
cols = ["Жарнама шығыны", "Көрілім", "Клиент саны", "Тапсырыс саны", "Сатылым көлемі", "Пайда"]

print("Орташа мән (mean):\n", myData[cols].mean().round(2))
print("Медиана (median):\n", myData[cols].median())
print("Минимум (min):\n", myData[cols].min())
print("Максимум (max):\n", myData[cols].max())

print("\n" + "-" * 80)
print("Түсіндірме:")
print("Бұл тапсырмада 4 негізгі статистикалық функция қолданылды:\n• mean() — орташа арифметикалық мән; median() — реттелген қатардың дәл ортасындағы мән (медиана); min() — ең кіші мән; max() — ең үлкен мән.\nCSV бойынша талдау: 'Пайда' бағанының орташа мәні (134.76) мен медианасы (135.0) бір-біріне өте жақын, бұл деректердің симметриялы әрі біркелкі таралғанын көрсетеді. Сатылым көлемі 232-ден 817-ге дейін өзгереді (орташасы — 524.25).")
print("-" * 80)
