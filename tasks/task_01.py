# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: pd.read_csv(CSV_PATH) — 'students_data.csv' файлын ашып, оны Python ішіндегі
# DataFrame (электронды кесте) түрінде 'myData' айнымалысына сақтайды.
# ШАГ 1: pd.read_csv(CSV_PATH) открывает файл 'students_data.csv' и превращает его
# в таблицу Pandas (DataFrame), которую мы называем 'myData'.
myData = pd.read_csv(CSV_PATH)

# 2-ҚАДАМ: myData.head(10) — кестенің ең басындағы алғашқы 10 жолды (0-ден 9-ға дейін) алады,
# ал print(...) соны экранға (терминалға) басып шығарады.
# Егер жақша ішіне сан жазбасақ — myData.head() әдепкі бойынша алғашқы 5 жолды шығарады.
# ШАГ 2: myData.head(10) берет ровно первые 10 строк с начала таблицы (индексы от 0 до 9),
# а print(...) выводит их на экран. (Если написать просто head() без числа — выведет 5 строк).
print(myData.head(10))

