# -*- coding: utf-8 -*-
import pandas as pd
import numpy as np

pd.set_option('display.max_columns', None)
pd.set_option('display.width', 1000)

df = pd.read_csv('бытовая_техника_каталог_600.csv')

# 1. Өзінің CSV файлын жүктеп, алғашқы 10 жолын экранға шығару
print("--- 1. Алғашқы 10 жол ---")
print(df.head(10))

# 2. Жолдар мен бағандардың санын анықтап, баған атауларын шығару
print("--- 2. Жолдар, бағандар және атаулар ---")
print("Жолдар мен бағандар саны:", df.shape)
print("Баған атаулары:", df.columns.tolist())

# 3. Деректер типтерін және әр бағандағы бос емес мәндердің санын анықтау
print("--- 3. Деректер типтері мен бос емес мәндер саны ---")
print(df.info())
print("\nБос емес мәндер саны (count):\n", df.count())

# 4. Сандық бағандардың негізгі статистикалық сипаттамаларын алу
print("--- 4. Статистикалық сипаттамалар ---")
print(df.describe())

# 5. Әр бағандағы бірегей мәндердің санын анықтау
print("--- 5. Бірегей мәндер саны ---")
print(df.nunique())
print("\nБрендтер тізімі:", df['Бренд'].unique())
print("Санаттар тізімі:", df['Категория'].unique())

# 6. Бос мәнді тауып, әр бағандағы олардың санын есептеу
print("--- 6. Бос мәндер саны (Null) ---")
print(df.isnull().sum())

# 7. Бос мәнді жою немесе тиісті әдіспен толтыру
print("--- 7. Бос мәндерді жою және толтыру ---")
df_filled = df.fillna(0)
print("fillna(0) қолданғаннан кейінгі бос мәндер:\n", df_filled.isnull().sum())
df_clean = df.dropna()
print("\ndropna() қолданғаннан кейінгі жолдар саны:", len(df_clean))

# 8. Қайталанатын жолдарды анықтап, оларды жою
print("--- 8. Қайталанатын жолдар саны ---")
print("Дубликаттар:", df.duplicated().sum())
df = df.drop_duplicates()
print("drop_duplicates() кейінгі кесте өлшемі:", df.shape)

# 9. Бір немесе бірнеше бағанның дерек типін өзгерту
print("--- 9. Деректер типін өзгерту ---")
df['Рейтинг товара'] = df['Рейтинг товара'].astype(float)
df['Остаток на складе (шт)'] = pd.to_numeric(df['Остаток на складе (шт)'])
print("Рейтинг товара типі:", df['Рейтинг товара'].dtype)
print("Остаток на складе (шт) типі:", df['Остаток на складе (шт)'].dtype)

# 10. Бағандардың атауларын өзгерту және қажетсіз жазбаларды жою
print("--- 10. Баған атауын өзгерту және бағанды жою ---")
df_mod = df.rename(columns={'Бренд': 'Производитель'})
df_mod = df_mod.drop(columns=['Склад отгрузки'])
print("Жаңартылған бағандар тізімі:\n", df_mod.columns.tolist())

# 11. Сандық көрсеткіші орташа мәннен жоғары жолдарды таңдау
mean_price = df['Розничная цена (руб)'].mean()
above_avg = df[df['Розничная цена (руб)'] > mean_price]
print(f"--- 11. Бағасы орташа мәннен ({mean_price:.2f} руб.) жоғары тауарлар ---")
print("Тауарлар саны:", len(above_avg))
print(above_avg.head(5))

# 12. Екі немесе одан да көп шартқа сәйкес келетін жазбаларды іріктеу
filtered_data = df.loc[(df['Категория'] == 'Стиральные машины') & (df['Рейтинг товара'] > 4.5)]
print("--- 12. Стиральные машины (рейтинг > 4.5) ---")
print("Табылған тауарлар саны:", len(filtered_data))
print(filtered_data.head(5))

# 13. Таңдалған көрсеткіш бойынша ең үлкен мәндері бар 10 жазбаны табу
top_10 = df.nlargest(10, 'Розничная цена (руб)')
print("--- 13. Ең қымбат 10 тауар ---")
print(top_10[['Артикул', 'Категория', 'Бренд', 'Модель', 'Розничная цена (руб)']])

# 14. Ең кіші мәндері бар 5 жазбаны табу
bottom_5 = df.nsmallest(5, 'Розничная цена (руб)')
print("--- 14. Ең арзан 5 тауар ---")
print(bottom_5[['Артикул', 'Категория', 'Бренд', 'Модель', 'Розничная цена (руб)']])

# 15. Деректерді бір немесе бірнеше баған бойынша сұрыптау
sorted_data = df.sort_values(by=['Категория', 'Розничная цена (руб)'], ascending=[True, False])
print("--- 15. Категория және баға бойынша сұрыпталған деректер ---")
print(sorted_data.head(5))

# 16. Орташа мән, медиана, минимум және максимумды есептеу
print("--- 16. Статистикалық көрсеткіштер (Розничная цена) ---")
print("Орташа мән (mean):", round(df['Розничная цена (руб)'].mean(), 2))
print("Медиана (median):", round(df['Розничная цена (руб)'].median(), 2))
print("Минимум (min):", df['Розничная цена (руб)'].min())
print("Максимум (max):", df['Розничная цена (руб)'].max())

# 17. Стандартты ауытқу мен дисперсияны есептеу
print("--- 17. Стандартты ауытқу және дисперсия ---")
print("Стандартты ауытқу (std):", round(df['Розничная цена (руб)'].std(), 2))
print("Дисперсия (var):", round(df['Розничная цена (руб)'].var(), 2))

# 18. Таңдалған көрсеткіштің 25, 50 және 75-процентильдерін табу
print("--- 18. Квантильдер (25%, 50%, 75%) ---")
print(df['Розничная цена (руб)'].quantile([0.25, 0.50, 0.75]))

# 19. Ең жиі кездесетін мәнді анықтау (mode(), value_counts())
print("--- 19. Ең жиі кездесетін бренд (мода) ---")
print("Мода:", df['Бренд'].mode()[0])
print("\nБрендтер бойынша жиілік кестесі (ТОП-10):\n", df['Бренд'].value_counts().head(10))

# 20. Екі немесе бірнеше сандық баған арасындағы корреляцияны зерттеу
correlation = df['Розничная цена (руб)'].corr(df['Остаток на складе (шт)'])
print("--- 20. Баға мен қалдық арасындағы корреляция ---")
print("Корреляция (Розничная цена vs Остаток):", round(correlation, 4))
print("\nБарлық сандық бағандардың корреляция матрицасы:\n", df.corr(numeric_only=True).round(4))
