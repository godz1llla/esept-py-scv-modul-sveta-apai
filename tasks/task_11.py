import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('11. Сандық көрсеткіші (Пайда) орташа мәннен жоғары жолдарды таңдаңыз.')
print("Pandas әдістері:", 'Шарттар, mean()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
meanProfit = myData["Пайда"].mean()
print("Орташа пайда:", round(meanProfit, 2))

highProfit = myData[myData["Пайда"] > meanProfit]
print("Табылған жазбалар өлшемі:", highProfit.shape)
print(highProfit.head(10))

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• mean() әдісі арқылы 'Пайда' бағанының орташа арифметикалық мәні есептелді — ол 134.76 бірлікке тең.\n• Логикалық шарт myData[myData['Пайда'] > meanProfit] арқылы пайдасы 134.76-дан жоғары барлық жолдар сүзіліп алынды.\nCSV бойынша талдау: Барлығы 600 жазбаның ішінен пайдасы орташа деңгейден жоғары 303 жазба (50.5%) таңдалды. Кестеде олардың алғашқы 10 жолы көрсетілген.")
print("-" * 80)
