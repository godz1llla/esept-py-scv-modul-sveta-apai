# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('3. Деректер типтерін және әр бағандағы бос емес мәндердің санын анықтаңыз.')
print("Pandas әдістері:", 'info(), count()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
myData.info()
print("\nӘр бағандағы бос емес мәндер саны:")
print(myData.count())

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• info() әдісі кесте туралы толық техникалық мәлімет береді: жазбалар саны (600), бағандар тізімі, бос емес мәндер саны (Non-Null Count) және деректер типі (Dtype).\n• count() әдісі әр бағандағы бос емес (NaN емес) мәндер санын жеке есептейді.\nCSV бойынша талдау: Барлық 13 бағанда да 600 бос емес мән бар, яғни деректер жиынында қалып кеткен (бос) ұяшықтар жоқ. 7 баған (№, Жарнама шығыны, Көрілім, Клиент саны, Тапсырыс саны, Сатылым көлемі, Пайда) бүтін сандық int64 типінде, ал 6 баған (Күні, Өнім атауы, Қала, Жарнама түрі, Төлем түрі, Менеджер) мәтіндік (str/object) типінде сақталған.')
