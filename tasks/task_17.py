import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('17. Стандартты ауытқу мен дисперсияны есептеңіз.')
print("Pandas әдістері:", 'std(), var()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
cols = ["Жарнама шығыны", "Көрілім", "Клиент саны", "Тапсырыс саны", "Сатылым көлемі", "Пайда"]

print("Стандартты ауытқу (std):\n", myData[cols].std().round(2))
print("Дисперсия (var):\n", myData[cols].var().round(2))

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• std() (стандартты ауытқу) және var() (дисперсия) деректердің орташа мәннен қаншалықты алшақ шашырағанын көрсетеді (дисперсия — стандартты ауытқудың квадраты).\nCSV бойынша талдау: Ең үлкен ауытқу 'Көрілім' бағанында (std = 1888.97), себебі жарнама қаралымдары мыңдаған бірлікпен өлшенеді. Ал 'Пайда' бағанының стандартты ауытқуы 46.52, дисперсиясы 2164.22 болды.")
print("-" * 80)
