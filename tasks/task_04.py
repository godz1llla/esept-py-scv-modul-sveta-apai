pd.set_option("display.max_columns", None)

# Кесте жолдары келесі жолға тасымалданбай, бір қатарға кеңінен шығуы үшін енін 1000 таңбаға қоямыз:
# Устанавливаем ширину экрана 1000 символов, чтобы таблица выводилась ровно в одну линию:
pd.set_option("display.width", 1000)

# Осы файл жатқан 'tasks' папкасынан бір деңгей жоғары (негізгі папкаға) шығатын жолды табамыз:
# Находим путь к главной папке проекта (на один уровень выше папки 'tasks'):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Негізгі папканың ішіндегі 'students_data.csv' файлының толық мекенжайын құрастырамыз:
# Собираем полный путь к нашему файлу 'students_data.csv':
CSV_PATH = os.path.join(BASE_DIR, "students_data.csv")

# CSV файлды оқып, 'myData' деген айнымалыға (DataFrame кестесіне) жүктейміз:
# Читаем CSV-файл и сохраняем всю таблицу (600 студентов, 12 столбцов) в переменную 'myData':
myData = pd.read_csv(CSV_PATH)

# Тек сандық мәндері бар 6 бағанның атауларын жеке тізімге сақтап қоямыз (статистика есептеу үшін):
# Сохраняем список из 6 числовых столбцов (нужен для задач со статистикой):
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

print("=" * 80)
print('4. Сандық бағандардың негізгі статистикалық сипаттамаларын алыңыз.')
print("Pandas әдістері:", 'describe()')
print("=" * 80 + "\n")

# ==============================================================================
# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: myData.describe() — кестедегі ТЕК сандық бағандарды (Курс, Қатысу_пайызы, Аралық_бақылау,
# Емтихан_балы, GPA, Стипендия) автоматты түрде тауып, олардың 8 статистикалық көрсеткішін есептейді:
#   count — мәндер саны (600)
#   mean  — орташа арифметикалық мән
#   std   — стандартты ауытқу (орташа мәннен қаншалықты ауытқитыны)
#   min   — ең кіші мән (минимум)
#   25%   — төменгі квартиль (студенттердің 25%-ы осы саннан төмен)
#   50%   — медиана (қатардың дәл ортасындағы мән)
#   75%   — жоғарғы квартиль (студенттердің 75%-ы осы саннан төмен)
#   max   — ең үлкен мән (максимум)
# .round(2) — үтірден кейін тек 2 цифр қалдырып дөңгелектейді (оқуға ыңғайлы болу үшін).
# ШАГ 1: myData.describe() сама выбирает все числовые столбцы и считает для них всю статистику сразу,
# а .round(2) округляет длинные дроби до 2 знаков после запятой.
print(myData.describe().round(2))

# ==============================================================================
# НӘТИЖЕНІҢ ТҮСІНДІРМЕСІ (ОБЪЯСНЕНИЕ РЕЗУЛЬТАТА НА КАЗАХСКОМ И РУССКОМ):
# ==============================================================================
print("\n" + "-" * 80)
print("Түсіндірме (Қазақша):")
print('• describe() әдісі кестедегі барлық сандық бағандар бойынша негізгі статистикалық көрсеткіштерді (count, mean, std, min, 25%, 50%, 75%, max) автоматты түрде есептейді.\nCSV бойынша талдау: Орташа сабаққа қатысу — 83.59%, аралық бақылау орташасы — 79.13, емтихан орташасы — 79.45, орташа GPA — 2.98 (1.99-дан 3.96-ға дейін).')
print("-" * 80)
print("Подробное объяснение простыми словами (По-русски):")
print('1. Что делает .describe(): Это самая мощная команда для быстрого анализа! Одним вызовом она считает сразу 8 показателей для всех числовых столбцов (текстовые столбцы вроде ФИО и Факультета она автоматически пропускает):\n   - count: сколько записей (600)\n   - mean: среднее значение (например, средний GPA = 2.98, средний балл экзамена = 79.45)\n   - std: стандартное отклонение (разброс значений вокруг среднего)\n   - min / max: самое маленькое и самое большое значение (GPA от 1.99 до 3.96)\n   - 25%, 50%, 75%: квартили (50% — это медиана).\n2. Зачем нужен .round(2): Без него числа выводились бы с длинными хвостами после запятой, а с .round(2) — аккуратно до сотых.')
print("-" * 80)
