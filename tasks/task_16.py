# ==============================================================================
# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: Барлық 6 сандық бағанның тізімін анықтаймыз:
# ШАГ 1: Задаем список всех 6 числовых столбцов нашей таблицы:
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

# 2-ҚАДАМ: Төрт статистикалық көрсеткішті жеке-жеке есептеп, оларды бір әдемі кестеге (DataFrame) жинаймыз:
#   • .mean()   — орташа арифметикалық мән (барлық мәндердің қосындысын 600-ге бөлу)
#   • .median() — медиана (сандарды өсу ретімен тізгенде дәл ортасында тұрған сан)
#   • .min()    — ең кіші мән (минимум)
#   • .max()    — ең үлкен мән (максимум)
# ШАГ 2: Считаем 4 главных статистических показателя и собираем их в одну аккуратную таблицу stats_16:
#   • .mean()   — среднее арифметическое
#   • .median() — медиана (середина упорядоченного ряда чисел)
#   • .min()    — самое маленькое значение
#   • .max()    — самое большое значение
stats_16 = pd.DataFrame({
    "Орташа мән (mean)": myData[num_cols].mean().round(2),
    "Медиана (median)": myData[num_cols].median().round(2),
    "Минимум (min)": myData[num_cols].min(),
    "Максимум (max)": myData[num_cols].max()
})

# 3-ҚАДАМ: Дайын статистика кестесін экранға шығарамыз:
# ШАГ 3: Выводим итоговую таблицу на экран:
print(stats_16)

