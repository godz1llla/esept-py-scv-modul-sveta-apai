# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: myData.info() — кестенің «паспортын» экранға шығарады:
# әр бағанның атын, онда қанша бос емес (non-null) мән бар екенін және деректер типін (int64, float64, str).
# info() өзі экранға шығаратындықтан, оны print() ішіне салудың қажеті жоқ.
# ШАГ 1: myData.info() выводит полную сводку («паспорт») таблицы:
# сколько всего строк, список всех столбцов, сколько в них заполненных ячеек (600 non-null) и тип данных (Dtype).
myData.info()

# 2-ҚАДАМ: Бос жол (\n) тастап, тақырып шығарамыз:
# ШАГ 2: Выводим заголовок с отступом строки (\n):
print("\nӘр бағандағы бос емес мәндер саны:")

# 3-ҚАДАМ: myData.count() — әр бағандағы тек толтырылған (бос емес / NaN емес) ұяшықтарды санайды.
# Бізде барлық бағанда 600 шығады, себебі бірде-бір бос ұяшық жоқ.
# ШАГ 3: myData.count() считает количество заполненных (не пустых) ячеек в каждом столбце отдельно.
print(myData.count())

