print("Зачем менять типы данных и в чем разница между astype() и to_numeric():\n1. .astype(float) — прямой перевод типа: например, столбец 'Емтихан_балы' был целым числом (int64: 90), а стал дробным (float64: 90.0). Можно переводить в int, float, str.\n2. pd.to_numeric() — специальная функция для перевода строковых/смешанных столбцов в числа. Очень удобна параметром errors='coerce', который не выдает ошибку при плохих символах.")
print("-" * 80)
