import os
import pandas as pd

pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "students_data.csv")

myData = pd.read_csv(CSV_PATH)
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

print("=" * 80)
print('12. Екі немесе одан да көп шартқа сәйкес келетін жазбаларды іріктеңіз.')
print("Pandas әдістері:", 'loc[], логикалық операторлар (&, |)')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
# 1) & (ЖӘНЕ) операторы: Ақпараттық технологиялар факультеті + Грант + GPA > 3.2
filter_and = myData.loc[
    (myData["Факультет"] == "Ақпараттық технологиялар") &
    (myData["Оқу_түрі"] == "Грант") &
    (myData["GPA"] > 3.2)
]
print("1) АТ факультетінде грантта оқитын және GPA > 3.2 студенттер саны:", len(filter_and))

# 2) | (НЕМЕСЕ) операторы: Алматы НЕМЕСЕ Астана қаласынан келген студенттер
filter_or = myData.loc[(myData["Қала"] == "Алматы") | (myData["Қала"] == "Астана")]
print("2) Алматы немесе Астана қаласынан келген студенттер саны:", len(filter_or))
print(filter_and.head(8))

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• loc[] — жолдар мен бағандарды белгіленген логикалық шарттар бойынша іріктеп алу индексаторы.\n• & (ЖӘНЕ) операторы барлық шарттардың бір мезгілде орындалуын талап етеді, ал | (НЕМЕСЕ) операторы кемінде бір шарттың орындалуын тексереді.\nCSV бойынша талдау: Ақпараттық технологиялар факультетінде грантта оқитын әрі GPA балы 3.2-ден асатын 36 үздік студент табылды. Ал Алматы немесе Астана қалаларынан келген студенттер саны — 291.')
print("-" * 80)
