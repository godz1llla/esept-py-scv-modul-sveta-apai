import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('2. Жолдар мен бағандардың санын анықтап, баған атауларын шығарыңыз.')
print("Pandas әдістері:", 'shape, columns')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
print("Кесте өлшемі (shape):", myData.shape)
print("Жолдар саны:", myData.shape[0])
print("Бағандар саны:", myData.shape[1])
print("Баған атаулары:", myData.columns.tolist())

print("\n" + "-" * 80)
print("Түсіндірме:")
print('Бұл тапсырмада кестенің құрылымын анықтайтын екі атрибут қолданылды:\n• shape — DataFrame өлшемін (жолдар_саны, бағандар_саны) кортежі ретінде қайтарады. Біздің маркетингтік деректер жиыны 600 жолдан (жазбадан) және 13 бағаннан тұрады.\n• columns — кестедегі барлық 13 бағанның атауларын қайтарады, ал tolist() әдісі оларды Python тізімі ретінде ыңғайлы форматта шығарады.')
print("-" * 80)
