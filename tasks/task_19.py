import os
import pandas as pd

pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "students_data.csv")

myData = pd.read_csv(CSV_PATH)
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

print("=" * 80)
print('19. Ең жиі кездесетін мәнді анықтаңыз.')
print("Pandas әдістері:", 'mode(), value_counts()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
for col in ["Факультет", "Мамандық", "Қала", "Оқу_түрі"]:
    print(f"{col} модасы: {myData[col].mode()[0]}")
    print(myData[col].value_counts())
    print("-" * 40)

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• mode() — бағандағы ең жиі кездесетін мәнді (моданы) табады.\n• value_counts() — бағандағы әрбір бірегей мәннің қанша рет кездесетінін кему ретімен санап береді.\nCSV бойынша талдау: Ең көп студент оқитын факультет — 'Ақпараттық технологиялар' (209 студент), ең танымал мамандық — 'Математика' (97 студент), ең көп студент келген қала — 'Алматы' (173 студент), ал оқу түрі бойынша 'Грант' (371 студент) басым.")
print("-" * 80)
