import pandas as pd

# ==============================================================================
# Pandas кітапханасы арқылы CSV файлдарымен жұмыс істеу
# Орындаған: Орынбеков Губайдулла | Тобы: Инф-23-1
# Деректер жиынтығы: marketing_data.csv (600 жол, 13 баған)
# ==============================================================================

# ==============================================================================
# 1-БӨЛІМ. ДЕРЕКТЕРДІ БАСТАПҚЫ ЗЕРТТЕУ (1–5 тапсырмалар)
# ==============================================================================

# 1-тапсырма: Өзінің CSV файлын жүктеп, алғашқы 10 жолын экранға шығару
# Қолданылатын әдістер: 1) read_csv(), 2) head()
df = pd.read_csv("marketing_data.csv")
print("=== 1-тапсырма (1-әдіс: read_csv, 2-әдіс: head): Алғашқы 10 жол ===")
print(df.head(10))

# 2-тапсырма: Жолдар мен бағандардың санын анықтап, баған атауларын шығару
# Қолданылатын әдістер: 3) shape, 4) columns
print("\n=== 2-тапсырма (3-әдіс: shape, 4-әдіс: columns): Кесте өлшемі мен баған атаулары ===")
print(f"Кесте өлшемі (shape): {df.shape} -> Жолдар: {df.shape[0]}, Бағандар: {df.shape[1]}")
print("Баған атаулары (columns):", df.columns.tolist())

# 3-тапсырма: Деректер типтерін және әр бағандағы бос емес мәндердің санын анықтау
# Қолданылатын әдістер: 5) info(), 6) count()
print("\n=== 3-тапсырма (5-әдіс: info, 6-әдіс: count): Деректер типтері және бос емес мәндер ===")
df.info()
print("\nӘр бағандағы бос емес мәндер саны (count):")
print(df.count())

# 4-тапсырма: Сандық бағандардың негізгі статистикалық сипаттамаларын алу
# Қолданылатын әдіс: 7) describe()
print("\n=== 4-тапсырма (7-әдіс: describe): Сандық бағандардың статистикалық сипаттамалары ===")
print(df.describe())

# 5-тапсырма: Әр бағандағы бірегей мәндердің санын анықтау
# Қолданылатын әдістер: 8) nunique(), 9) unique()
print("\n=== 5-тапсырма (8-әдіс: nunique, 9-әдіс: unique): Бірегей мәндер ===")
print("Әр бағандағы бірегей мәндер саны (nunique):")
print(df.nunique())
print("Қалалар тізімі (unique):", df["Қала"].unique())
print("Өнім атаулары (unique):", df["Өнім атауы"].unique())
print("Жарнама түрлері (unique):", df["Жарнама түрі"].unique())


# ==============================================================================
# 2-БӨЛІМ. ДЕРЕКТЕРДІ ТАЗАЛАУ ЖӘНЕ АЛДЫН АЛА ӨҢДЕУ (6–10 тапсырмалар)
# ==============================================================================

# 6-тапсырма: Бос мәндерді тауып, әр бағандағы олардың санын есептеу
# Қолданылатын әдістер: 10) isnull(), 11) sum()
print("\n=== 6-тапсырма (10-әдіс: isnull, 11-әдіс: sum): Бос мәндер саны ===")
print(df.isnull().sum())

# 7-тапсырма: Бос мәндерді жою немесе тиісті әдіспен толтыру
# Қолданылатын әдістер: 12) dropna(), 13) fillna()
print("\n=== 7-тапсырма (12-әдіс: dropna, 13-әдіс: fillna): Бос мәндерді жою және толтыру ===")
df_dropped_na = df.dropna()
df = df.fillna(0)
print("dropna() кейінгі өлшем:", df_dropped_na.shape)
print("fillna(0) кейінгі өлшем:", df.shape)

# 8-тапсырма: Қайталанатын жолдарды анықтап, оларды жою
# Қолданылатын әдістер: 14) duplicated(), 15) drop_duplicates()
print("\n=== 8-тапсырма (14-әдіс: duplicated, 15-әдіс: drop_duplicates): Дубликаттарды тексеру ===")
print("Қайталанатын жолдар саны (duplicated):", df.duplicated().sum())
df = df.drop_duplicates()
print("drop_duplicates() кейінгі жолдар саны:", len(df))

# 9-тапсырма: Бір немесе бірнеше бағанның деректер типін өзгерту
# Қолданылатын әдістер: 16) astype(), 17) to_numeric()
print("\n=== 9-тапсырма (16-әдіс: astype, 17-әдіс: to_numeric): Деректер типін өзгерту ===")
df["Жарнама шығыны"] = df["Жарнама шығыны"].astype(float)
df["Пайда"] = pd.to_numeric(df["Пайда"], errors="coerce")
print(df[["Жарнама шығыны", "Пайда"]].dtypes)

# 10-тапсырма: Бағандардың атауларын өзгерту және қажетсіз бағандарды жою
# Қолданылатын әдістер: 18) rename(), 19) drop()
print("\n=== 10-тапсырма (18-әдіс: rename, 19-әдіс: drop): Баған атауын өзгерту және жою ===")
df = df.rename(columns={"Төлем түрі": "Төлем_әдісі"})
df = df.drop(columns=["№"])
print("Жаңартылған бағандар тізімі:", df.columns.tolist())


# ==============================================================================
# 3-БӨЛІМ. ДЕРЕКТЕРДІ СҮЗГІЛЕУ ЖӘНЕ СҰРЫПТАУ (11–15 тапсырмалар)
# ==============================================================================

# 11-тапсырма: Сандық көрсеткіші орташа мәннен жоғары жолдарды таңдау
# Қолданылатын әдіс: 20) Шарттар және mean()
print("\n=== 11-тапсырма (20-әдіс: шарт + mean): Пайдасы орташа мәннен жоғары жолдар ===")
mean_profit = df["Пайда"].mean()
above_mean_df = df[df["Пайда"] > mean_profit]
print(f"Орташа пайда: {mean_profit:.2f}, Табылған жолдар саны: {len(above_mean_df)}")
print(above_mean_df.head())

# 12-тапсырма: Екі немесе одан да көп шартқа сәйкес келетін жазбаларды іріктеу
# Қолданылатын әдіс: 21) loc[] және логикалық операторлар (&, |)
print("\n=== 12-тапсырма (21-әдіс: loc[] және &): Алматы қаласы және Instagram жарнамасы ===")
filtered_df = df.loc[(df["Қала"] == "Алматы") & (df["Жарнама түрі"] == "Instagram")]
print(f"Табылған жазбалар саны: {len(filtered_df)}")
print(filtered_df.head())

# 13-тапсырма: Таңдалған көрсеткіш бойынша ең үлкен мәндері бар 10 жазбаны табу
# Қолданылатын әдіс: 22) nlargest()
print("\n=== 13-тапсырма (22-әдіс: nlargest): Сатылым көлемі ең үлкен 10 жазба ===")
print(df.nlargest(10, "Сатылым көлемі")[["Күні", "Өнім атауы", "Қала", "Сатылым көлемі", "Пайда"]])

# 14-тапсырма: Ең кіші мәндері бар 5 жазбаны табу
# Қолданылатын әдіс: 23) nsmallest()
print("\n=== 14-тапсырма (23-әдіс: nsmallest): Пайдасы ең кіші 5 жазба ===")
print(df.nsmallest(5, "Пайда")[["Күні", "Өнім атауы", "Қала", "Сатылым көлемі", "Пайда"]])

# 15-тапсырма: Деректерді бір немесе бірнеше баған бойынша сұрыптау
# Қолданылатын әдіс: 24) sort_values()
print("\n=== 15-тапсырма (24-әдіс: sort_values): Қала және Пайда бойынша сұрыптау ===")
sorted_df = df.sort_values(by=["Қала", "Пайда"], ascending=[True, False])
print(sorted_df[["Күні", "Қала", "Өнім атауы", "Сатылым көлемі", "Пайда"]].head(10))


# ==============================================================================
# 4-БӨЛІМ. СТАТИСТИКАЛЫҚ ТАЛДАУ (16–20 тапсырмалар)
# ==============================================================================

# 16-тапсырма: Сандық көрсеткіштердің орташа мәнін, медианасын, минимумын және максимумын есептеу
# Қолданылатын әдістер: 25) mean(), 26) median(), 27) min(), 28) max()
print("\n=== 16-тапсырма (25–28 әдістер: mean, median, min, max): 'Пайда' көрсеткіштері ===")
print(f"25) Орташа мәні (mean):  {df['Пайда'].mean():.2f}")
print(f"26) Медианасы (median):  {df['Пайда'].median():.2f}")
print(f"27) Минимумы (min):      {df['Пайда'].min()}")
print(f"28) Максимумы (max):     {df['Пайда'].max()}")

# 17-тапсырма: Стандартты ауытқу мен дисперсияны есептеу
# Қолданылатын әдістер: 29) std(), 30) var()
print("\n=== 17-тапсырма (29-әдіс: std, 30-әдіс: var): Стандартты ауытқу мен дисперсия ===")
print(f"29) Стандартты ауытқу (std): {df['Пайда'].std():.2f}")
print(f"30) Дисперсия (var):         {df['Пайда'].var():.2f}")

# 18-тапсырма: Таңдалған көрсеткіштің 25, 50 және 75-процентильдерін табу
# Қолданылатын әдіс: 31) quantile()
print("\n=== 18-тапсырма (31-әдіс: quantile): 25%, 50% және 75% процентильдер ===")
print(df["Сатылым көлемі"].quantile([0.25, 0.50, 0.75]))

# 19-тапсырма: Ең жиі кездесетін мәнді анықтау
# Қолданылатын әдістер: 32) mode(), 33) value_counts()
print("\n=== 19-тапсырма (32-әдіс: mode, 33-әдіс: value_counts): Ең жиі кездесетін мән ===")
print("Ең жиі кездесетін өнім (mode):", df["Өнім атауы"].mode()[0])
print("\nӨнімдердің кездесу жиілігі (value_counts):")
print(df["Өнім атауы"].value_counts())

# 20-тапсырма: Екі немесе бірнеше сандық баған арасындағы корреляцияны зерттеу
# Қолданылатын әдіс: 34) corr()
print("\n=== 20-тапсырма (34-әдіс: corr): Сандық бағандар арасындағы корреляция ===")
num_cols = ["Жарнама шығыны", "Көрілім", "Клиент саны", "Тапсырыс саны", "Сатылым көлемі", "Пайда"]
print(df[num_cols].corr().round(3))
