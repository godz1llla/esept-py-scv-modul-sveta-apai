import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('7. Бос мәндерді жойыңыз немесе тиісті әдіспен толтырыңыз.')
print("Pandas әдістері:", 'dropna(), fillna()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
cleanData = myData.dropna()
print("dropna() кейінгі өлшем:", cleanData.shape)

filled = myData.copy()
filled["Пайда"] = filled["Пайда"].fillna(filled["Пайда"].mean())
filled["Сатылым көлемі"] = filled["Сатылым көлемі"].fillna(filled["Сатылым көлемі"].median())
print("fillna() кейінгі бос мәндер саны:", filled.isnull().sum().sum())

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• dropna() әдісі құрамында кем дегенде бір бос (NaN) мәні бар жолдарды кестеден толықтай өшіреді.\n• fillna() әдісі бос ұяшықтарды өшірмей, оларды көрсетілген мәнмен (мысалы, бағанның орташа мәні mean() немесе медианасы median() арқылы) толтырады.\nCSV бойынша талдау: Бастапқы кестеде бос мәндер болмағандықтан, dropna() қолданғаннан кейін де кесте өлшемі (600, 13) өзгеріссіз қалды, ал fillna() арқылы өңделген көшірмеде де бос мәндер саны 0 болды.')
print("-" * 80)
