print("Как работает сортировка .sort_values():\n1. Параметр by=['Факультет', 'GPA'] говорит: сначала сгруппируй по алфавиту факультеты, а внутри одного факультета расставь студентов по GPA.\n2. Параметр ascending (по возрастанию): если True — сортирует от меньшего к большему (или от А до Я); если False — сортирует по убыванию (от большего к меньшему, чтобы отличники были наверху).")
print("-" * 80)
