import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('5. Әр бағандағы бірегей мәндердің санын анықтаңыз.')
print("Pandas әдістері:", 'nunique(), unique()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
print(myData.nunique())

for col in ["Өнім атауы", "Қала", "Жарнама түрі", "Төлем түрі", "Менеджер"]:
    print(col, "->", myData[col].nunique(), ":", myData[col].unique())

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• nunique() әдісі әр бағанда неше қайталанбайтын (бірегей) мән бар екенін санайды.\n• unique() әдісі таңдалған бағандағы сол бірегей мәндердің нақты тізімін массив түрінде шығарады.\nCSV бойынша талдау: Деректер жиынында 4 түрлі тауар (Телефон, Ноутбук, Құлаққап, Планшет), 4 қала (Алматы, Астана, Шымкент, Қызылорда), 3 жарнама арнасы (Instagram, TikTok, Google), 2 төлем түрі (Kaspi, Halyk) және 3 менеджер (Айдана, Данияр, Аружан) бар екені анықталды.')
print("-" * 80)
