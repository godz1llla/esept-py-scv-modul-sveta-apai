import pandas as pd

# ==============================================================================
# 1-БӨЛІМ. ДЕРЕКТЕРДІ БАСТАПҚЫ ЗЕРТТЕУ (1–5 тапсырмалар)
# ==============================================================================

# 1-тапсырма: Өзінің CSV файлын жүктеп, алғашқы 10 жолын экранға шығару (read_csv(), head())
df = pd.read_csv("marketing_data.csv")
print("=== 1-тапсырма: Алғашқы 10 жол ===")
print(df.head(10))

# 2-тапсырма: Жолдар мен бағандардың санын анықтап, баған атауларын шығару (shape, columns)
print("\n=== 2-тапсырма: Жолдар мен бағандар саны және баған атаулары ===")
print(f"Кесте өлшемі (shape): {df.shape}")
print(f"Жолдар саны: {df.shape[0]}, Бағандар саны: {df.shape[1]}")
print("Баған атаулары:", df.columns.tolist())

# 3-тапсырма: Деректер типтерін және әр бағандағы бос емес мәндердің санын анықтау (info(), count())
print("\n=== 3-тапсырма: Деректер типтері (info) және бос емес мәндер саны (count) ===")
df.info()
print("\nӘр бағандағы бос емес мәндер саны:")
print(df.count())

# 4-тапсырма: Сандық бағандардың негізгі статистикалық сипаттамаларын алу (describe())
print("\n=== 4-тапсырма: Сандық бағандардың статистикалық сипаттамалары ===")
print(df.describe())

# 5-тапсырма: Әр бағандағы бірегей мәндердің санын анықтау (nunique(), unique())
print("\n=== 5-тапсырма: Әр бағандағы бірегей мәндер саны ===")
print(df.nunique())
print("Қалалар тізімі (unique):", df["Қала"].unique())
print("Өнім атаулары (unique):", df["Өнім атауы"].unique())
print("Жарнама түрлері (unique):", df["Жарнама түрі"].unique())


# ==============================================================================
# 2-БӨЛІМ. ДЕРЕКТЕРДІ ТАЗАЛАУ ЖӘНЕ АЛДЫН АЛА ӨҢДЕУ (6–10 тапсырмалар)
# ==============================================================================

# 6-тапсырма: Бос мәндерді тауып, әр бағандағы олардың санын есептеу (isnull(), sum())
print("\n=== 6-тапсырма: Әр бағандағы бос (NaN) мәндер саны ===")
print(df.isnull().sum())

# 7-тапсырма: Бос мәндерді жою немесе тиісті әдіспен толтыру (dropna(), fillna())
print("\n=== 7-тапсырма: Бос мәндерді жою немесе толтыру ===")
df = df.fillna(0)
df = df.dropna()
print("Бос мәндерді тексергеннен кейінгі кесте өлшемі:", df.shape)

# 8-тапсырма: Қайталанатын жолдарды анықтап, оларды жою (duplicated(), drop_duplicates())
print("\n=== 8-тапсырма: Қайталанатын жолдарды (дубликаттарды) анықтау және жою ===")
dup_count = df.duplicated().sum()
print(f"Қайталанатын жолдар саны: {dup_count}")
df = df.drop_duplicates()
print("Дубликаттарды жойғаннан кейінгі жолдар саны:", len(df))

# 9-тапсырма: Бір немесе бірнеше бағанның деректер типін өзгерту (astype(), to_numeric())
print("\n=== 9-тапсырма: Бағандардың деректер типін өзгерту ===")
df["Жарнама шығыны"] = df["Жарнама шығыны"].astype(float)
df["Пайда"] = pd.to_numeric(df["Пайда"], errors="coerce")
print(df[["Жарнама шығыны", "Пайда"]].dtypes)

# 10-тапсырма: Бағандардың атауларын өзгерту және қажетсіз бағандарды жою (rename(), drop())
print("\n=== 10-тапсырма: Баған атауын өзгерту және қажетсіз бағанды жою ===")
df = df.rename(columns={"Төлем түрі": "Төлем_әдісі"})
df = df.drop(columns=["№"])
print("Жаңартылған бағандар тізімі:", df.columns.tolist())


# ==============================================================================
# 3-БӨЛІМ. ДЕРЕКТЕРДІ СҮЗГІЛЕУ ЖӘНЕ СҰРЫПТАУ (11–15 тапсырмалар)
# ==============================================================================

# 11-тапсырма: Сандық көрсеткіші орташа мәннен жоғары жолдарды таңдау (Шарттар, mean())
print("\n=== 11-тапсырма: Пайдасы орташа мәннен жоғары жолдарды таңдау ===")
mean_profit = df["Пайда"].mean()
above_mean_df = df[df["Пайда"] > mean_profit]
print(f"Орташа пайда: {mean_profit:.2f}")
print(f"Орташа мәннен жоғары жазбалар саны: {len(above_mean_df)}")
print(above_mean_df.head())

# 12-тапсырма: Екі немесе одан да көп шартқа сәйкес келетін жазбаларды іріктеу (loc[], логикалық операторлар)
print("\n=== 12-тапсырма: Екі шарт бойынша іріктеу (Алматы қаласы және Instagram жарнамасы) ===")
filtered_df = df.loc[(df["Қала"] == "Алматы") & (df["Жарнама түрі"] == "Instagram")]
print(f"Сәйкес келетін жазбалар саны: {len(filtered_df)}")
print(filtered_df.head())

# 13-тапсырма: Таңдалған көрсеткіш бойынша ең үлкен мәндері бар 10 жазбаны табу (nlargest())
print("\n=== 13-тапсырма: Сатылым көлемі бойынша ең үлкен 10 жазба ===")
top_10_sales = df.nlargest(10, "Сатылым көлемі")
print(top_10_sales[["Күні", "Өнім атауы", "Қала", "Сатылым көлемі", "Пайда"]])

# 14-тапсырма: Ең кіші мәндері бар 5 жазбаны табу (nsmallest())
print("\n=== 14-тапсырма: Пайдасы ең аз 5 жазба ===")
bottom_5_profit = df.nsmallest(5, "Пайда")
print(bottom_5_profit[["Күні", "Өнім атауы", "Қала", "Сатылым көлемі", "Пайда"]])

# 15-тапсырма: Деректерді бір немесе бірнеше баған бойынша сұрыптау (sort_values())
print("\n=== 15-тапсырма: Қала және Пайда бойынша сұрыптау ===")
sorted_df = df.sort_values(by=["Қала", "Пайда"], ascending=[True, False])
print(sorted_df[["Күні", "Қала", "Өнім атауы", "Сатылым көлемі", "Пайда"]].head(10))


# ==============================================================================
# 4-БӨЛІМ. СТАТИСТИКАЛЫҚ ТАЛДАУ (16–20 тапсырмалар)
# ==============================================================================

# 16-тапсырма: Сандық көрсеткіштердің орташа мәнін, медианасын, минимумын және максимумын есептеу (mean(), median(), min(), max())
print("\n=== 16-тапсырма: 'Пайда' бағанының орташа мәні, медианасы, минимумы және максимумы ===")
print(f"Орташа мәні (mean):  {df['Пайда'].mean():.2f}")
print(f"Медианасы (median):  {df['Пайда'].median():.2f}")
print(f"Минимумы (min):      {df['Пайда'].min()}")
print(f"Максимумы (max):     {df['Пайда'].max()}")

# 17-тапсырма: Стандартты ауытқу мен дисперсияны есептеу (std(), var())
print("\n=== 17-тапсырма: 'Пайда' бағанының стандартты ауытқуы мен дисперсиясы ===")
print(f"Стандартты ауытқу (std): {df['Пайда'].std():.2f}")
print(f"Дисперсия (var):         {df['Пайда'].var():.2f}")

# 18-тапсырма: Таңдалған көрсеткіштің 25, 50 және 75-процентильдерін табу (quantile())
print("\n=== 18-тапсырма: 'Сатылым көлемі' көрсеткішінің 25%, 50% және 75% процентильдері ===")
percentiles = df["Сатылым көлемі"].quantile([0.25, 0.50, 0.75])
print(percentiles)

# 19-тапсырма: Ең жиі кездесетін мәнді анықтау (mode(), value_counts())
print("\n=== 19-тапсырма: Ең жиі кездесетін мәнді анықтау (mode және value_counts) ===")
print("Ең жиі кездесетін өнім атауы (mode):", df["Өнім атауы"].mode()[0])
print("\nӨнімдердің кездесу жиілігі (value_counts):")
print(df["Өнім атауы"].value_counts())

# 20-тапсырма: Екі немесе бірнеше сандық баған арасындағы корреляцияны зерттеу (corr())
print("\n=== 20-тапсырма: Сандық бағандар арасындағы корреляция матрицасы ===")
num_cols = ["Жарнама шығыны", "Көрілім", "Клиент саны", "Тапсырыс саны", "Сатылым көлемі", "Пайда"]
corr_matrix = df[num_cols].corr()
print(corr_matrix.round(3))
