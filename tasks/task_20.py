# os кітапханасы — компьютердегі файлдар мен папкалардың жолын (путь) табу үшін керек
# Модуль os нужен для работы с путями к файлам и папкам на компьютере
import os

# pandas кітапханасын импорттап, оған қысқаша 'pd' деген ат береміз (кестелермен жұмыс істеу үшін)
# Импортируем библиотеку pandas под коротким именем 'pd' (главная библиотека для таблиц)
import pandas as pd

# Кестенің барлық 12 бағаны экранға толық сыйып, ортасынан '...' болып қиылмауы үшін баптау:
# Настройка, чтобы при выводе таблицы в терминал показывались ВСЕ столбцы без сокращения '...':
pd.set_option("display.max_columns", None)

# Кесте жолдары келесі жолға тасымалданбай, бір қатарға кеңінен шығуы үшін енін 1000 таңбаға қоямыз:
# Устанавливаем ширину экрана 1000 символов, чтобы таблица выводилась ровно в одну линию:
pd.set_option("display.width", 1000)

# Осы файл жатқан 'tasks' папкасынан бір деңгей жоғары (негізгі папкаға) шығатын жолды табамыз:
# Находим путь к главной папке проекта (на один уровень выше папки 'tasks'):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Негізгі папканың ішіндегі 'students_data.csv' файлының толық мекенжайын құрастырамыз:
# Собираем полный путь к нашему файлу 'students_data.csv':
CSV_PATH = os.path.join(BASE_DIR, "students_data.csv")

# CSV файлды оқып, 'myData' деген айнымалыға (DataFrame кестесіне) жүктейміз:
# Читаем CSV-файл и сохраняем всю таблицу (600 студентов, 12 столбцов) в переменную 'myData':
myData = pd.read_csv(CSV_PATH)

# Тек сандық мәндері бар 6 бағанның атауларын жеке тізімге сақтап қоямыз (статистика есептеу үшін):
# Сохраняем список из 6 числовых столбцов (нужен для задач со статистикой):
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

print("=" * 80)
print('20. Екі немесе бірнеше сандық баған арасындағы корреляцияны зерттеңіз.')
print("Pandas әдістері:", 'corr()')
print("=" * 80 + "\n")

# ==============================================================================
# НЕГІЗГІ КОД (ОСНОВНОЙ КОД ЗАДАЧИ С ПОСТРОЧНЫМ ОБЪЯСНЕНИЕМ):
# ==============================================================================
# 1-ҚАДАМ: myData[num_cols].corr() — барлық 6 сандық бағанның бір-бірімен өзара байланысын
# (Пирсон корреляция матрицасын) есептейді.
# Корреляция коэффициенті -1 мен +1 аралығында болады:
#   • +1-ге жақын болса (мысалы, 0.93 немесе 0.85) — күшті ОҢ байланыс (біреуі өссе, екіншісі де өседі).
#   • 0-ге жақын болса (мысалы, 0.04) — байланыс ЖОҚ (біріне-бірі әсер етпейді).
#   • -1-ге жақын болса — ТЕРІС (кері) байланыс (біреуі өссе, екіншісі кемиді).
# ШАГ 1: myData[num_cols].corr() строит таблицу (матрицу) корреляции между всеми числовыми столбцами.
# Коэффициент корреляции показывает силу связи от -1 до +1:
#   • Близко к +1 (например, 0.93 между Емтихан_балы и GPA) — сильная прямая связь: выше экзамен -> выше GPA!
#   • Около 0 (например, 0.04 у Курса) — связи нет (GPA не зависит от того, на каком курсе учится студент).
corr_matrix = myData[num_cols].corr().round(2)

# 2-ҚАДАМ: Корреляция матрицасын экранға шығарамыз:
# ШАГ 2: Выводим матрицу корреляции на экран:
print("Корреляция матрицасы:")
print(corr_matrix)

# ==============================================================================
# НӘТИЖЕНІҢ ТҮСІНДІРМЕСІ (ОБЪЯСНЕНИЕ РЕЗУЛЬТАТА НА КАЗАХСКОМ И РУССКОМ):
# ==============================================================================
print("\n" + "-" * 80)
print("Түсіндірме (Қазақша):")
print('• corr() — сандық бағандар арасындағы сызықтық тәуелділікті (Пирсон корреляция коэффициентін, -1-ден +1-ге дейін) есептейді.\nCSV бойынша талдау:\n  1) Емтихан_балы мен GPA арасында r = 0.93 және Аралық_бақылау мен GPA арасында r = 0.85 — өте күшті оң корреляция бар.\n  2) Қатысу_пайызы мен GPA арасында r = 0.71 — сабаққа көп қатысқан студенттердің балы жоғары.\n  3) GPA мен Стипендия арасында r = 0.40 — GPA жоғары болған сайын стипендия мөлшері де өседі.')
print("-" * 80)
print("Подробное объяснение простыми словами (По-русски):")
print("Что такое корреляция .corr() простыми словами:\nКорреляция показывает, зависит ли один показатель от другого (принимает значения от -1 до +1):\n1. На диагонали таблицы всегда стоят 1.00 — потому что каждый столбец сам с собой совпадает на 100%.\n2. Между 'Емтихан_балы' и 'GPA' корреляция равна 0.93 (93%), а между 'Аралық_бақылау' и 'GPA' — 0.85 (85%). Это очень сильная прямая связь: чем лучше студент сдал рубежку и экзамен, тем выше его GPA.\n3. Между 'Қатысу_пайызы' (посещаемостью) и 'GPA' корреляция 0.71 — кто ходит на пары, у того высокий балл.\n4. А у столбца 'Курс' со всеми баллами корреляция около 0 (0.04) — значит, успеваемость не зависит от номера курса.")
print("-" * 80)
