import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('9. Бір немесе бірнеше бағанның деректер типін өзгертіңіз.')
print("Pandas әдістері:", 'astype(), to_numeric()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
data2 = myData.copy()
data2["Жарнама шығыны"] = data2["Жарнама шығыны"].astype(float)
data2["Сатылым көлемі"] = data2["Сатылым көлемі"].astype(float)
data2["Пайда"] = pd.to_numeric(data2["Пайда"], errors="coerce")
print(data2[["Жарнама шығыны", "Сатылым көлемі", "Пайда"]].dtypes)

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• astype(float) әдісі бағанның деректер типін көрсетілген жаңа типке (бұл жерде бүтін int64 типінен нақты float64 типіне) тікелей ауыстырады.\n• pd.to_numeric(..., errors='coerce') функциясы баған мәндерін сандық форматқа айналдырады (қате мәтін кездессе, оны NaN ретінде белгілейді).\nCSV бойынша талдау: 'Жарнама шығыны' және 'Сатылым көлемі' бағандары бөлшек есептеулер жүргізу үшін float64 типіне ауыстырылды, ал 'Пайда' бағаны сандық int64 типінде тексерілді.")
print("-" * 80)
