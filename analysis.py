# Тақырыбы: Университет студенттерінің үлгерімін Pandas арқылы талдау (students_data.csv)

import pandas as pd

pd.set_option('display.max_columns', None)
pd.set_option('display.width', 1000)

myData = pd.read_csv("students_data.csv")

# ============================================================================
# 1. Өзіңіздің CSV файлыңызды жүктеп, алғашқы 10 жолын экранға шығарыңыз. (read_csv(), head())
# ============================================================================
print(myData.head(10))

# ============================================================================
# 2. Жолдар мен бағандардың санын анықтап, баған атауларын шығарыңыз. (shape, columns)
# ============================================================================
print("Кесте өлшемі (shape):", myData.shape)
print("Жолдар саны:", myData.shape[0])
print("Бағандар саны:", myData.shape[1])
print("Баған атаулары:", myData.columns.tolist())

# ============================================================================
# 3. Деректер типтерін және әр бағандағы бос емес мәндердің санын анықтаңыз. (info(), count())
# ============================================================================
myData.info()
print("\nӘр бағандағы бос емес мәндер саны:")
print(myData.count())

# ============================================================================
# 4. Сандық бағандардың негізгі статистикалық сипаттамаларын алыңыз. (describe())
# ============================================================================
print(myData.describe().round(2))

# ============================================================================
# 5. Әр бағандағы бірегей мәндердің санын анықтаңыз. (nunique(), unique())
# ============================================================================
print("Әр бағандағы бірегей мәндер саны:")
print(myData.nunique())
print("\nФакультеттер:", myData["Факультет"].unique())
print("Мамандықтар:", myData["Мамандық"].unique())
print("Қалалар:", myData["Қала"].unique())
print("Оқу түрі:", myData["Оқу_түрі"].unique())

# ============================================================================
# 6. Бос мәндерді тауып, әр бағандағы олардың санын есептеңіз. (isnull(), sum())
# ============================================================================
print("Әр бағандағы бос (NaN) мәндер саны:")
print(myData.isnull().sum())
print("Жалпы бос мәндер саны:", myData.isnull().sum().sum())

# ============================================================================
# 7. Бос мәндерді жою немесе тиісті әдіспен толтыру. (dropna(), fillna())
# ============================================================================
clean_drop = myData.dropna()
clean_fill = myData.copy()
clean_fill["GPA"] = clean_fill["GPA"].fillna(clean_fill["GPA"].mean())
clean_fill["Факультет"] = clean_fill["Факультет"].fillna("Белгісіз")
print("dropna() кейінгі кесте өлшемі:", clean_drop.shape)
print("fillna() кейінгі бос мәндер саны:", clean_fill.isnull().sum().sum())

# ============================================================================
# 8. Қайталанатын жолдарды анықтап, оларды жойыңыз. (duplicated(), drop_duplicates())
# ============================================================================
dup_count = myData.duplicated().sum()
print("Қайталанатын (дубликат) жолдар саны:", dup_count)
myData_no_dup = myData.drop_duplicates()
print("Дубликаттарды жойғаннан кейінгі өлшем:", myData_no_dup.shape)

# ============================================================================
# 9. Бір немесе бірнеше бағанның деректер типін өзгертіңіз. (astype(), to_numeric())
# ============================================================================
myData_types = myData.copy()
myData_types["Емтихан_балы"] = myData_types["Емтихан_балы"].astype(float)
myData_types["GPA"] = pd.to_numeric(myData_types["GPA"], errors="coerce")
print("Өзгертілген деректер типтері:")
print(myData_types[["Емтихан_балы", "GPA", "Курс"]].dtypes)

# ============================================================================
# 10. Бағандардың атауларын өзгерту және қажетсіз бағандарды жою. (rename(), drop())
# ============================================================================
myData_renamed = myData.rename(columns={"Оқу_түрі": "Оқу_негізі"})
myData_dropped = myData_renamed.drop(columns=["Студент_ID"])
print("Жаңартылған бағандар саны:", myData_dropped.shape[1])
print("Жаңартылған баған атаулары:", myData_dropped.columns.tolist())
print(myData_dropped.head(5))

# ============================================================================
# 11. Сандық көрсеткіші (мысалы, GPA) орташа мәннен жоғары жолдарды таңдаңыз. (Шарттар, mean())
# ============================================================================
mean_gpa = myData["GPA"].mean()
above_avg = myData[myData["GPA"] > mean_gpa]
print(f"Орташа GPA: {mean_gpa:.2f}")
print(f"GPA көрсеткіші орташадан жоғары студенттер саны: {len(above_avg)} (600 ішінен)")
print(above_avg.head(10))

# ============================================================================
# 12. Екі немесе одан да көп шартқа сәйкес келетін жазбаларды іріктеңіз. (loc[], логикалық операторлар (&, |))
# ============================================================================
# 1) & (ЖӘНЕ) операторы: Ақпараттық технологиялар факультеті + Грант + GPA > 3.2
filter_and = myData.loc[
    (myData["Факультет"] == "Ақпараттық технологиялар") &
    (myData["Оқу_түрі"] == "Грант") &
    (myData["GPA"] > 3.2)
]
print("1) АТ факультетінде грантта оқитын және GPA > 3.2 студенттер саны:", len(filter_and))

# 2) | (НЕМЕСЕ) операторы: Алматы НЕМЕСЕ Астана қаласынан келген студенттер
filter_or = myData.loc[(myData["Қала"] == "Алматы") | (myData["Қала"] == "Астана")]
print("2) Алматы немесе Астана қаласынан келген студенттер саны:", len(filter_or))
print(filter_and.head(8))

# ============================================================================
# 13. Таңдалған көрсеткіш бойынша ең үлкен мәндері бар 10 жазбаны табыңыз. (nlargest())
# ============================================================================
top10_exam = myData.nlargest(10, "Емтихан_балы")
print(top10_exam[["Студент_ID", "Аты_жөні", "Факультет", "Мамандық", "Курс", "Қала", "Емтихан_балы", "GPA", "Стипендия"]])

# ============================================================================
# 14. Ең кіші мәндері бар 5 жазбаны табыңыз. (nsmallest())
# ============================================================================
bottom5_gpa = myData.nsmallest(5, "GPA")
print(bottom5_gpa[["Студент_ID", "Аты_жөні", "Факультет", "Мамандық", "Курс", "Қала", "Қатысу_пайызы", "Емтихан_балы", "GPA"]])

# ============================================================================
# 15. Деректерді бір немесе бірнеше баған бойынша сұрыптаңыз. (sort_values())
# ============================================================================
sorted_data = myData.sort_values(by=["Факультет", "GPA"], ascending=[True, False])
print(sorted_data[["Студент_ID", "Аты_жөні", "Факультет", "Мамандық", "Курс", "Емтихан_балы", "GPA", "Стипендия"]].head(10))

# ============================================================================
# 16. Сандық көрсеткіштердің орташа мәнін, медианасын, минимумын және максимумын есептеңіз. (mean(), median(), min(), max())
# ============================================================================
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]
stats_16 = pd.DataFrame({
    "Орташа мән (mean)": myData[num_cols].mean().round(2),
    "Медиана (median)": myData[num_cols].median().round(2),
    "Минимум (min)": myData[num_cols].min(),
    "Максимум (max)": myData[num_cols].max()
})
print(stats_16)

# ============================================================================
# 17. Стандартты ауытқу мен дисперсияны есептеңіз. (std(), var())
# ============================================================================
stats_17 = pd.DataFrame({
    "Стандартты ауытқу (std)": myData[num_cols].std().round(2),
    "Дисперсия (var)": myData[num_cols].var().round(2)
})
print(stats_17)

# ============================================================================
# 18. Таңдалған көрсеткіштің 25, 50 және 75-процентильдерін табыңыз. (quantile())
# ============================================================================
q_table = myData[["GPA", "Емтихан_балы", "Қатысу_пайызы"]].quantile([0.25, 0.50, 0.75])
print(q_table)

# ============================================================================
# 19. Ең жиі кездесетін мәнді анықтаңыз. (mode(), value_counts())
# ============================================================================
for col in ["Факультет", "Мамандық", "Қала", "Оқу_түрі"]:
    print(f"{col} модасы: {myData[col].mode()[0]}")
    print(myData[col].value_counts())
    print("-" * 40)

# ============================================================================
# 20. Екі немесе бірнеше сандық баған арасындағы корреляцияны зерттеңіз. (corr())
# ============================================================================
corr_matrix = myData[num_cols].corr().round(3)
print(corr_matrix)
