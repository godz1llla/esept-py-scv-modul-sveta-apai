import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('10. Бағандардың атауларын өзгертіп және қажетсіз бағандарды жойыңыз.')
print("Pandas әдістері:", 'rename(), drop()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
data3 = myData.rename(columns={
    "Төлем түрі": "Төлем_әдісі",
    "Жарнама шығыны": "Шығын",
    "Сатылым көлемі": "Түсім"
})
data3 = data3.drop(columns=["№"])
print("Жаңа бағандар:", data3.columns.tolist())
print("Жаңа өлшем:", data3.shape)

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• rename(columns={...}) әдісі сөздік арқылы баған атауларын ыңғайлы жаңа атауларға өзгертеді ('Төлем түрі' -> 'Төлем_әдісі', 'Жарнама шығыны' -> 'Шығын', 'Сатылым көлемі' -> 'Түсім').\n• drop(columns=['№']) әдісі талдауға қажет емес '№' (реттік нөмір) бағанын кестеден өшіреді.\nCSV бойынша талдау: Нәтижесінде кестедегі бағандар саны 13-тен 12-ге азайды, ал баған атаулары қысқа әрі түсінікті болды.")
print("-" * 80)
