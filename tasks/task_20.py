import os
import pandas as pd

pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "students_data.csv")

myData = pd.read_csv(CSV_PATH)
num_cols = ["Курс", "Қатысу_пайызы", "Аралық_бақылау", "Емтихан_балы", "GPA", "Стипендия"]

print("=" * 80)
print('20. Екі немесе бірнеше сандық баған арасындағы корреляцияны зерттеңіз.')
print("Pandas әдістері:", 'corr()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
corr_matrix = myData[num_cols].corr().round(3)
print(corr_matrix)

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• corr() — сандық бағандар арасындағы Пирсонның сызықтық корреляция коэффициенттерінің матрицасын (-1 мен +1 аралығында) есептейді.\nCSV бойынша талдау: Кестеде өте күшті оң корреляция байқалады:\n1) Сабаққа қатысу пайызы мен Аралық бақылау арасындағы байланыс r = 0.694, ал GPA-мен байланысы r = 0.711.\n2) Емтихан балы мен GPA арасындағы корреляция r = 0.926 (өте тығыз байланыс).\n3) GPA мен Стипендия мөлшері арасында да айқын оң корреляция бар (r = 0.400), яғни сабаққа тұрақты қатысып, жоғары балл жинаған студенттер жоғары GPA мен шәкіртақыға ие болады.')
print("-" * 80)
