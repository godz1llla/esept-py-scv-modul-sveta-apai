import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('14. Ең кіші мәндері бар 5 жазбаны табыңыз.')
print("Pandas әдістері:", 'nsmallest()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
bottom5 = myData.nsmallest(5, "Пайда")
print(bottom5[["№", "Күні", "Өнім атауы", "Қала", "Жарнама түрі", "Сатылым көлемі", "Пайда"]])

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• nsmallest(5, 'Пайда') әдісі 'Пайда' көрсеткіші бойынша ең төменгі 5 жазбаны таңдап шығарады.\nCSV бойынша талдау: Деректердегі ең аз пайда — 48 бірлік (29.09.2026 күні Астана қаласында TikTok арқылы сатылған Планшет). Одан кейінгі төменгі көрсеткіштер 49 және 51 бірлікті құрайды.")
print("-" * 80)
