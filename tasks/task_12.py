import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('12. Екі немесе одан да көп шартқа сәйкес келетін жазбаларды іріктеңіз.')
print("Pandas әдістері:", 'loc[], логикалық операторлар (&, |)')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
# 1-мысал: ЖӘНЕ (&) операторы — Алматы қаласы, Instagram жарнамасы және Пайда > 100
result1 = myData.loc[(myData["Қала"] == "Алматы") & (myData["Жарнама түрі"] == "Instagram") & (myData["Пайда"] > 100)]
print("1-сүзгі өлшемі:", result1.shape)
print(result1.head(8))

# 2-мысал: НЕМЕСЕ (|) операторы — Алматы немесе Астана қалалары
result2 = myData.loc[(myData["Қала"] == "Алматы") | (myData["Қала"] == "Астана"),
                     ["Күні", "Өнім атауы", "Қала", "Жарнама түрі", "Сатылым көлемі", "Пайда"]]
print("2-сүзгі өлшемі:", result2.shape)

print("\n" + "-" * 80)
print("Түсіндірме:")
print('• loc[] индексаторы мен логикалық & (ЖӘНЕ), | (НЕМЕСЕ) операторлары бірнеше шартты біріктіріп сүзгілеуге мүмкіндік береді.\nCSV бойынша талдау: Бірінші сұраныста үш шарт бір мезгілде орындалатын (қаласы — Алматы, жарнамасы — Instagram және пайдасы 100-ден жоғары) 36 жазба табылды. Ал екінші сұраныста | (НЕМЕСЕ) операторы арқылы Алматы немесе Астана қалаларына тиесілі 300 жазба іріктелді.')
print("-" * 80)
