print("• dropna() — кемінде бір ұяшығы бос (NaN) болған жолдарды кестеден толықтай өшіреді.\n• fillna() — бос ұяшықтарды өшірмей, оларды белгілі бір мәнмен (орташа мәнмен немесе 'Белгісіз' сөзімен) толтырады.\nCSV бойынша талдау: Бастапқы деректерде бос ұяшықтар болмағандықтан, барлық 600 жол өзгеріссіз сақталды.")
print("-" * 80)
print("Подробное объяснение простыми словами (По-русски):")
print("Когда в таблице есть пустые ячейки (пропуски), в Pandas есть 2 главных метода:\n1. dropna() (от англ. drop NA — выбросить пустые): удаляет всю строку целиком, если в ней пропущено значение.\n2. fillna() (от англ. fill NA — заполнить пустые): не удаляет строку, а вписывает вместо пустоты указанное значение (для чисел обычно подставляют среднее .mean() или 0, а для текста — слово 'Белгісіз').")
print("-" * 80)
