import os
import pandas as pd

# Кестенің барлық бағандары экранға толық сыюы үшін баптау:
pd.set_option("display.max_columns", None)
pd.set_option("display.width", 1000)

# CSV файлдың жолын автоматты түрде табу (кез келген папкадан іске қосылады):
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(BASE_DIR, "marketing_data.csv")

myData = pd.read_csv(CSV_PATH)

print("=" * 80)
print('20. Екі немесе бірнеше сандық баған арасындағы корреляцияны зерттеңіз.')
print("Pandas әдістері:", 'corr()')
print("=" * 80 + "\n")

# --- НЕГІЗГІ КОД ---
corrCols = ["Жарнама шығыны", "Көрілім", "Клиент саны", "Тапсырыс саны", "Сатылым көлемі", "Пайда"]
print(myData[corrCols].corr().round(3))
print("Жарнама шығыны мен Пайда корреляциясы:", round(myData["Жарнама шығыны"].corr(myData["Пайда"]), 4))

print("\n" + "-" * 80)
print("Түсіндірме:")
print("• corr() әдісі сандық бағандар арасындағы сызықтық байланыс тығыздығын (Пирсонның корреляция коэффициентін -1 мен +1 аралығында) есептейді.\nCSV бойынша талдау: Барлық маркетингтік көрсеткіштер арасында өте күшті оң корреляция (0.989 – 0.994) байқалады. Мысалы, 'Жарнама шығыны' мен 'Көрілім' арасындағы корреляция 0.994, ал 'Жарнама шығыны' мен 'Пайда' арасындағы корреляция 0.989. Бұл жарнамаға салынған инвестиция өскен сайын көрілім, клиент саны, тапсырыс көлемі және таза пайда да тікелей пропорционалды түрде өсетінін дәлелдейді.")
print("-" * 80)
